import React, { useState } from 'react';
import { JobAnalysisResponse } from '../types';
import { RiskScoreGauge } from './RiskScoreGauge';
import { WarningsBreakdown } from './WarningsBreakdown';
import { RecommendationsCard } from './RecommendationsCard';
import { 
  Building2, 
  MapPin, 
  Calendar, 
  RotateCcw, 
  Share2, 
  Flag, 
  Check, 
  ExternalLink,
  ShieldCheck,
  Info
} from 'lucide-react';

interface ResultCardProps {
  result: JobAnalysisResponse;
  onReset: () => void;
  onOpenReportModal: (result: JobAnalysisResponse) => void;
}

export const ResultCard: React.FC<ResultCardProps> = ({
  result,
  onReset,
  onOpenReportModal
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopyReport = () => {
    const textSummary = `[VeriJob AI Risk Report]
Job: ${result.job_title} at ${result.company_name}
Risk Score: ${result.risk_score}/100 (${result.risk_level} Risk)
ML Semantic Probability: ${result.ml_score}%
Rule Heuristic Risk: ${result.rule_score}%
Warnings Detected: ${result.warning_signs.length}
${result.warning_signs.map((w, i) => `  ${i + 1}. [${w.severity.toUpperCase()}] ${w.title}: ${w.description}`).join('\n')}
Analysis Date: ${new Date(result.created_at).toLocaleString()}
Generated by VeriJob AI - Fake Job & Internship Detection System`;

    navigator.clipboard.writeText(textSummary);
    setCopied(true);
    setTimeout(() => setCopied(false), 3000);
  };

  return (
    <div className="space-y-6 animate-fadeIn">
      {/* Top Header Card */}
      <div className="glass-panel rounded-2xl p-6 sm:p-8 border-slate-800">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="flex items-center space-x-2 text-xs font-semibold uppercase tracking-wider text-blue-400 mb-1.5">
              <span>Analysis Report ID: {result.id.substring(0, 8)}...</span>
            </div>
            <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">
              {result.job_title}
            </h1>
            <div className="flex flex-wrap items-center gap-3 mt-2 text-sm text-slate-300">
              <span className="flex items-center space-x-1.5 font-semibold text-slate-200">
                <Building2 className="w-4 h-4 text-purple-400" />
                <span>{result.company_name}</span>
              </span>
              {result.location && (
                <span className="flex items-center space-x-1 text-slate-400">
                  <MapPin className="w-4 h-4 text-emerald-400" />
                  <span>{result.location}</span>
                </span>
              )}
              {result.job_type && (
                <span className="px-2.5 py-0.5 rounded-full text-xs font-medium bg-slate-800 text-slate-300 border border-slate-700">
                  {result.job_type}
                </span>
              )}
              {result.salary_stipend && (
                <span className="text-xs text-amber-300 font-medium bg-amber-950/30 px-2 py-0.5 rounded border border-amber-500/20">
                  Offered: {result.salary_stipend}
                </span>
              )}
            </div>
          </div>

          <div className="flex items-center space-x-2.5">
            <button
              onClick={handleCopyReport}
              className="px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-800 hover:border-slate-700 text-xs font-semibold text-slate-300 hover:text-white flex items-center space-x-1.5 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Share2 className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard!' : 'Share Summary'}</span>
            </button>
            <button
              onClick={() => onOpenReportModal(result)}
              className="px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-800 hover:border-rose-500/40 text-xs font-semibold text-rose-300 hover:text-rose-200 flex items-center space-x-1.5 transition-colors"
            >
              <Flag className="w-3.5 h-3.5 text-rose-400" />
              <span>Report Scam</span>
            </button>
            <button
              onClick={onReset}
              className="px-4 py-2 rounded-xl bg-blue-600 hover:bg-blue-500 text-white text-xs font-bold flex items-center space-x-1.5 shadow-md shadow-blue-500/20 transition-all"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>New Analysis</span>
            </button>
          </div>
        </div>
      </div>

      {/* Main Grid: Gauge & Explanations */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        <div className="lg:col-span-5">
          <RiskScoreGauge
            score={result.risk_score}
            level={result.risk_level}
            mlScore={result.ml_score}
            ruleScore={result.rule_score}
            modelMode={result.model_mode}
          />
        </div>

        <div className="lg:col-span-7 space-y-4">
          <div className="glass-panel rounded-2xl p-6 border-slate-800 h-full flex flex-col justify-between">
            <div>
              <h3 className="text-base font-bold text-white flex items-center space-x-2 mb-3">
                <Info className="w-4 h-4 text-blue-400" />
                <span>Why This Score Was Calculated</span>
              </h3>
              
              {result.explanations.length > 0 ? (
                <div className="space-y-3">
                  {result.explanations.map((exp, idx) => (
                    <div key={idx} className="bg-slate-900/70 p-3.5 rounded-xl border border-slate-800">
                      <div className="flex items-center justify-between mb-1">
                        <h4 className="text-sm font-semibold text-slate-100">{exp.title}</h4>
                        <span className="text-xs font-bold text-amber-400">{exp.impact}</span>
                      </div>
                      <p className="text-xs text-slate-300 leading-relaxed">{exp.detail}</p>
                    </div>
                  ))}
                </div>
              ) : (
                <p className="text-sm text-slate-400 leading-relaxed">
                  No adversarial patterns, hidden payment requirements, or identity mismatches were observed. The posting text matches typical verified recruitment language.
                </p>
              )}
            </div>

            {/* Recruiter Email & URL verification status */}
            <div className="mt-4 pt-4 border-t border-slate-800/80 grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
              <div className="bg-slate-900/50 p-2.5 rounded-lg border border-slate-800/80">
                <span className="text-slate-500 block mb-0.5">Recruiter Contact:</span>
                <span className="font-mono text-slate-300 truncate block">
                  {result.recruiter_email || 'None provided'}
                </span>
              </div>
              <div className="bg-slate-900/50 p-2.5 rounded-lg border border-slate-800/80">
                <span className="text-slate-500 block mb-0.5">Application Portal:</span>
                <span className="font-mono text-slate-300 truncate block">
                  {result.application_url || 'None provided'}
                </span>
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Warnings Section */}
      <WarningsBreakdown warnings={result.warning_signs} />

      {/* Recommendations Section */}
      <RecommendationsCard recommendations={result.recommendations} />

      {/* Bottom Floating Bar */}
      <div className="p-4 rounded-xl bg-slate-900/90 border border-slate-800 flex items-center justify-between text-xs text-slate-400">
        <div className="flex items-center space-x-2">
          <ShieldCheck className="w-4 h-4 text-blue-400" />
          <span>Results saved to your local session history</span>
        </div>
        <button
          onClick={onReset}
          className="text-blue-400 hover:text-blue-300 font-semibold"
        >
          Analyze another posting →
        </button>
      </div>
    </div>
  );
};
